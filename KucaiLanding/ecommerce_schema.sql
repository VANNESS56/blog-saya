-- ─── DIGITAL PRODUCTS ───
CREATE TABLE IF NOT EXISTS digital_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL, -- e.g., 'AKUN', 'LAYANAN'
  title TEXT NOT NULL,
  description TEXT,
  price NUMERIC NOT NULL,
  icon TEXT, -- nama icon dari lucide-react, misal: 'Mail', 'Shield'
  status TEXT DEFAULT 'TERSEDIA',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- RLS Digital Products (Publik bisa membaca)
ALTER TABLE digital_products ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public read digital_products" ON digital_products;
CREATE POLICY "Public read digital_products" ON digital_products FOR SELECT USING (true);

